"""Copy the author credits from credits.json into every place that shows them.

    python engine/tools/apply_credits.py

Writes: engine/credits.py (reports), app/ui/credits.js (app and splash), app/ui/author.<ext> (photo),
app/build/installer.nsh + installer images + license.txt (Windows installer), CITATION.cff and the author
fields of app/package.json. Run it after editing credits.json; the build scripts run it automatically.
"""
import json
import os
import re
import shutil
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
APP = os.path.join(ROOT, "app")
BUILD = os.path.join(APP, "build")
UI = os.path.join(APP, "ui")

SPRUCE = (47, 93, 80)
SPRUCE_DARK = (24, 48, 42)
RAIL = (18, 39, 31)
OCHRE = (224, 178, 82)
WHITE = (255, 255, 255)


def load():
    with open(os.path.join(ROOT, "credits.json"), encoding="utf-8") as f:
        c = json.load(f)
    c.pop("_help", None)
    c.setdefault("display_name", f"{c.get('given_name', '')} {c.get('family_name', '')}".strip())
    with open(os.path.join(APP, "package.json"), encoding="utf-8") as f:
        c["version"] = json.load(f)["version"]
    return c


def holder(c):
    return c.get("copyright_holder") or c["display_name"]


def write_funding(c):
    """GitHub 'Sponsor' button."""
    links = [u for u in (c.get("paypal"), c.get("revolut")) if u]
    os.makedirs(os.path.join(ROOT, ".github"), exist_ok=True)
    p = os.path.join(ROOT, ".github", "FUNDING.yml")
    if links:
        with open(p, "w", encoding="utf-8") as f:
            f.write("# Generated by engine/tools/apply_credits.py from credits.json\ncustom: [" +
                    ", ".join(f'"{u}"' for u in links) + "]\n")
    elif os.path.exists(p):
        os.remove(p)


def initials(c):
    w = [x for x in c["display_name"].split() if x]
    return ((w[0][0] + w[-1][0]) if len(w) > 1 else w[0][:2]).upper() if w else ""


def cite_name(c):
    """APA-style 'Rehman, N. U.'"""
    given = " ".join(p[0] + "." for p in c.get("given_name", "").split() if p)
    return f"{c['family_name']}, {given}".strip(", ")


def copy_photo(c):
    for old in ("author.jpg", "author.jpeg", "author.png", "author.webp"):
        p = os.path.join(UI, old)
        if os.path.exists(p):
            os.remove(p)
    src = c.get("photo") or ""
    if not src:
        return ""
    src = src if os.path.isabs(src) else os.path.join(ROOT, src)
    if not os.path.isfile(src):
        print(f"  photo not found: {src} (the app shows initials instead)")
        return ""
    ext = os.path.splitext(src)[1].lower()
    name = "author" + (ext if ext in (".jpg", ".jpeg", ".png", ".webp") else ".jpg")
    try:
        from PIL import Image
        im = Image.open(src).convert("RGB")
        side = min(im.size)
        left, top = (im.width - side) // 2, (im.height - side) // 3
        im = im.crop((left, top, left + side, top + side)).resize((360, 360))
        name = "author.jpg"
        im.save(os.path.join(UI, name), quality=88)
    except Exception:
        shutil.copyfile(src, os.path.join(UI, name))
    return name


