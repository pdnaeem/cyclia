def _font(size, bold=False):
    from PIL import ImageFont
    bundled = os.path.join(UI, "fonts", "Inter-SemiBold.woff" if bold else "Inter-Regular.woff")
    try:
        return ImageFont.truetype(bundled, size)
    except Exception:
        pass
    names = (["segoeuib.ttf", "arialbd.ttf", "DejaVuSans-Bold.ttf", "Helvetica-Bold.ttf"] if bold else
             ["segoeui.ttf", "arial.ttf", "DejaVuSans.ttf", "Helvetica.ttf"])
    dirs = ["", r"C:\Windows\Fonts", "/usr/share/fonts/truetype/dejavu", "/Library/Fonts", "/System/Library/Fonts"]
    for n in names:
        for d in dirs:
            try:
                return ImageFont.truetype(os.path.join(d, n) if d else n, size)
            except Exception:
                continue
    try:
        return ImageFont.load_default(size=size)
    except TypeError:
        return ImageFont.load_default()


def _wrap(draw, text, font, width):
    words, lines, cur = text.split(), [], ""
    for w in words:
        t = (cur + " " + w).strip()
        if draw.textlength(t, font=font) <= width:
            cur = t
        else:
            lines.append(cur)
            cur = w
    if cur:
        lines.append(cur)
    return lines


