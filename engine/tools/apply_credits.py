def write_citation(c):
    y = lambda s: '"' + str(s).replace('"', "'") + '"'
    lines = [
        "cff-version: 1.2.0",
        'message: "If you use Cyclia in a thesis or publication, please cite it as below."',
        f"title: {y(c['software_title'])}",
        "abstract: >-",
        "  Desktop software for life cycle assessment following ISO 14040/44, without programming. It reads the",
        "  user's own databases (ecoinvent, openLCA JSON-LD, SimaPro CSV, ILCD, ecoSpold1), solves the matrix model,",
        "  and provides uncertainty and sensitivity analysis, background scenarios, standards outputs (EN 15804+A2,",
        "  PEF, ISO 14067) and an automatic validation against ecoinvent's own results.",
        "type: software",
        "authors:",
        f"  - family-names: {y(c['family_name'])}",
        f"    given-names: {y(c['given_name'])}",
    ]
    if c.get("orcid"):
        o = c["orcid"].replace("https://orcid.org/", "")
        lines.append(f"    orcid: {y('https://orcid.org/' + o)}")
    if c.get("affiliations"):
        lines.append(f"    affiliation: {y('; '.join(c['affiliations']))}")
    if c.get("email"):
        lines.append(f"    email: {y(c['email'])}")
    for p in c.get("contributors") or []:
        if isinstance(p, dict) and p.get("family_name"):
            lines.append(f"  - family-names: {y(p['family_name'])}")
            lines.append(f"    given-names: {y(p.get('given_name', ''))}")
    if c.get("repository"):
        lines.append(f"repository-code: {y(c['repository'])}")
    if c.get("website"):
        lines.append(f"url: {y(c['website'])}")
    if c.get("doi"):
        lines.append(f"doi: {y(c['doi'])}")
    lines += ["license: MIT", f'version: "{c["version"]}"', "keywords:", "  - life cycle assessment", "  - LCA",
              "  - ISO 14044", "  - ecoinvent", "  - environmental footprint", ""]
    with open(os.path.join(ROOT, "CITATION.cff"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def write_package(c):
    p = os.path.join(APP, "package.json")
    with open(p, encoding="utf-8") as f:
        pkg = json.load(f)
    pkg["author"] = {"name": c["display_name"], "email": c.get("email") or c.get("support_email") or ""}
    if c.get("website"):
        pkg["homepage"] = c["website"]
    pkg["build"]["copyright"] = f"Copyright (c) {c['year']} {holder(c)} and the Cyclia contributors (MIT licence)"
    m = re.match(r"https://github\.com/([^/]+)/([^/#?]+)", c.get("repository") or "")
    if m:
        for pub in pkg["build"].get("publish", []):
            if pub.get("provider") == "github":
                pub["owner"], pub["repo"] = m.group(1), m.group(2).removesuffix(".git")
    with open(p, "w", encoding="utf-8") as f:
        json.dump(pkg, f, indent=2, ensure_ascii=False)
        f.write("\n")


def write_license(c):
    p = os.path.join(ROOT, "LICENSE")
    with open(p, encoding="utf-8") as f:
        txt = f.read()
    txt = re.sub(r"Copyright \(c\) .*", f"Copyright (c) {c['year']} {holder(c)} and the Cyclia contributors", txt, count=1)
    with open(p, "w", encoding="utf-8") as f:
        f.write(txt)


def main():
    c = load()
    photo = copy_photo(c)
    write_license(c)
    write_engine(c)
    write_ui(c, photo)
    write_installer(c)
    write_citation(c)
    write_package(c)
    write_funding(c)
    shutil.copyfile(os.path.join(ROOT, "docs", "USER_GUIDE.md"), os.path.join(UI, "guide.md"))  # in-app guide
    print(f"Credits applied for {c['display_name']} (Cyclia {c['version']})" + (f", photo {photo}" if photo else ""))


if __name__ == "__main__":
    sys.exit(main())
