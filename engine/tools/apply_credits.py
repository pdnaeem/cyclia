def write_ui(c, photo):
    data = dict(c)
    data["photo"] = photo
    data["initials"] = initials(c)
    data["cite_name"] = cite_name(c)
    with open(os.path.join(UI, "credits.js"), "w", encoding="utf-8") as f:
        f.write("/* Generated by engine/tools/apply_credits.py from credits.json. Edit credits.json, not this file. */\n")
        f.write("window.CREDITS = " + json.dumps(data, indent=2, ensure_ascii=False) + ";\n")


def nsis_text(s):
    return s.replace("$", "$$").replace('"', "'").replace("\n", "$\\r$\\n")


